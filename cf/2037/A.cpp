void solve() {
  unordered_map<int, int> mp;
  int n;
  cin >> n;
  while (n--) {
    int a;
    cin >> a;
    mp[a]++;
  }
  int ans = 0;
  for (auto it = mp.begin(); it != mp.end(); ++it) {
    ans += it->second / 2;
  }
  cout << ans << '\n';
}

